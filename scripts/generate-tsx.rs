//! Generate the Native Shell entry's imports from the same tables as the code tabs.

use std::{fs, io, path::Path};

include!("../apps/docs/src/gallery_tsx.in");

fn main() -> io::Result<()> {
    let output = Path::new(".nsh");
    let wrappers = output.join("gallery-examples");
    fs::create_dir_all(&wrappers)?;

    let mut imports = String::from("// Generated by scripts/docs-web.sh.\n");
    let mut entries = String::new();

    macro_rules! tsx_examples {
        ($($id:ident => $path:literal, $export:ident;)*) => {{
            $(
                imports.push_str(concat!(
                    "import { ", stringify!($export), " as example_", stringify!($id),
                    " } from \"../apps/docs/src/", $path, "\";\n",
                ));
                entries.push_str(concat!("  ", stringify!($id), ": example_", stringify!($id), ",\n"));
            )*
        }};
    }

    macro_rules! gallery_examples {
        ($($page:ident $component:ident $factory:ident $label:literal => $render:path, $rsx:literal;)*) => {{
            $(
                fs::write(
                    wrappers.join(concat!(stringify!($component), ".tsx")),
                    gallery_tsx!($component),
                )?;
                imports.push_str(concat!(
                    "import { Example as ", stringify!($component),
                    " } from \"./gallery-examples/", stringify!($component), "\";\n",
                ));
                entries.push_str(concat!("  ", stringify!($component), ",\n"));
            )*
        }};
    }

    include!("../apps/docs/src/tsx_examples.in");
    include!("../apps/docs/src/gallery_examples.in");
    fs::write(
        output.join("examples.generated.ts"),
        format!("{imports}\nexport const examples = new Map(Object.entries({{\n{entries}}}));\n"),
    )
}
